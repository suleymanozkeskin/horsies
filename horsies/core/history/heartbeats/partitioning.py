"""Hourly heartbeat leaves: registration, create-ahead, expiry sweep.

The heartbeat class registers into the shared retention-class table with
a horizon DERIVED from the configured staleness thresholds — heartbeats
matter only while they can refute a staleness verdict, so retention is
`max(stale_after, finalizing_stale_after) x safety_factor` with a
one-hour floor, recomputed from configuration at every registration and
never a constant. Because the horizon is operational drop cadence rather
than a promise snapshotted onto requests, a changed configuration
UPDATES the stored duration (a typed outcome) instead of conflicting —
the immutability rule that protects history classes protects enqueue
snapshots, and nothing snapshots the heartbeat class.

Leaves are hourly, cataloged in the shared leaf catalog under the
reserved class key, and detached/dropped by the same manager machinery
history leaves use — `detach_expired_leaf` and `drop_detached_leaf` are
interval-agnostic, and a heartbeat leaf can never be pending-blocked
because no pending locator carries the reserved class. Creation is
heartbeat-specific: the per-leaf index is the stale probe's
`(task_id, role, sent_at DESC)` shape, not the history task-ID index,
and no loader republish accompanies it because the manifest excludes the
reserved class at assembly. Bounded relations per transaction: one leaf.

Registration requires the partitioned parent to exist: parent creation
belongs to the install and migration programs, and a deployment still on
the unpartitioned table is a typed refusal, not hidden DDL.
"""

