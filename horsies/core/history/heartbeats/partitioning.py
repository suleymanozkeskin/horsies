_HOURLY = timedelta(hours=1)
_HORIZON_FLOOR = timedelta(hours=1)

HEARTBEATS_PARTITIONED_DDL = f"""
CREATE TABLE {HEARTBEATS_TABLE} (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    task_id uuid NOT NULL,
    sender_id varchar(255) NOT NULL,
    role varchar(20) NOT NULL,
    sent_at timestamptz NOT NULL,
    hostname varchar(255),
    pid integer
) PARTITION BY RANGE (sent_at)
"""
"""The cutover shape: RANGE on `sent_at` directly (no LIST parent —
heartbeats have no retention classes and never enter history), created
EMPTY at migration because heartbeats are transient. `task_id` is uuid,
not the current varchar(36): post-cutover task identity is uuid, the
stale probe compares against the live `id` column directly, and an
empty-at-cutover table owes the old encoding nothing. No primary key: a
partitioned key would have to include `sent_at`, and no reader addresses
heartbeats by identity. The retention-serving `sent_at` index does not
carry over; retention is leaf drop."""


def hourly_leaf_name(lower: datetime) -> str:
    """The leaf relation name for the hour starting at `lower`."""
    name = f'{HEARTBEATS_TABLE}_{lower:%Y_%m_%d_%H}'
    if not is_safe_identifier(name):
        raise ValueError(f'{name!r} is not a safe identifier')
    return name


def probe_index_name(leaf_name: str) -> str:
    """The per-leaf stale-probe index name."""
    name = f'{leaf_name}_probe_idx'
    if not is_safe_identifier(name):
        raise ValueError(f'{name!r} is not a safe identifier')
    return name


def heartbeat_horizon(
    *,
    stale_after: timedelta,
    finalizing_stale_after: timedelta,
    safety_factor: int,
) -> timedelta:
    """Derive the heartbeat retention horizon from staleness thresholds.

    `max(stale_after, finalizing_stale_after) x safety_factor`, floored
    at one hour. All three inputs come from configuration; none is a
    constant here.
    """
    if stale_after <= timedelta(0) or finalizing_stale_after <= timedelta(0):
        raise ValueError('staleness thresholds must be positive')
    if safety_factor < 1:
        raise ValueError('safety factor must be at least 1')
    derived = max(stale_after, finalizing_stale_after) * safety_factor
    return max(derived, _HORIZON_FLOOR)


# ---------------------------------------------------------------------------
# Class registration
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class HeartbeatClassRegistered:
    """The heartbeat class row now exists with the derived horizon."""

    horizon: timedelta


@dataclass(frozen=True, slots=True)
class HeartbeatClassVerified:
    """An identical registration already exists; nothing changed."""

    horizon: timedelta


@dataclass(frozen=True, slots=True)
class HeartbeatHorizonUpdated:
    """Configuration changed the derived horizon; the stored duration
    was updated. Drop cadence shifts; nothing else does."""

    previous_horizon: timedelta
    horizon: timedelta


@dataclass(frozen=True, slots=True)
class HeartbeatParentUnpartitioned:
    """The heartbeat table exists but is not partitioned — the deployment
    has not run the cutover migration. Registration refuses."""


type HeartbeatClassRegistration = (
    HeartbeatClassRegistered
    | HeartbeatClassVerified
    | HeartbeatHorizonUpdated
    | HeartbeatParentUnpartitioned
)


async def register_heartbeat_class(
    connection: AsyncConnection,
    *,
    horizon: timedelta,
) -> HeartbeatClassRegistration:
    """Create, verify, or update the heartbeat class registration.

    Requires the partitioned parent to already exist; a deployment still
    on the unpartitioned table receives a typed refusal.
    """
    if horizon < _HORIZON_FLOOR:
        raise ValueError('heartbeat horizon is floored at one hour')

    partitioned = (
        await connection.execute(
            text(
                """
                SELECT EXISTS (
                    SELECT 1 FROM pg_partitioned_table
                    WHERE partrelid = to_regclass(:parent)
                )
                """
            ),
            {'parent': HEARTBEATS_TABLE},
        )
    ).scalar_one()
    if not partitioned:
        return HeartbeatParentUnpartitioned()

    existing = await read_retention_class(connection, HEARTBEAT_CLASS_KEY)
    match existing:
        case None:
            await connection.execute(
                text(
                    f"""
                    INSERT INTO {RETENTION_CLASSES} (
                        class_key, duration, partition_interval,
                        finite_parent_name, created_at
                    ) VALUES (
                        :class_key, :duration, :interval,
                        :parent, statement_timestamp()
                    )
                    """
                ),
                {
                    'class_key': HEARTBEAT_CLASS_KEY,
                    'duration': horizon,
                    'interval': _HOURLY,
                    'parent': HEARTBEATS_TABLE,
                },
            )
            return HeartbeatClassRegistered(horizon=horizon)
        case RetentionClassRow(
            duration=timedelta() as stored,
            partition_interval=interval,
            finite_parent_name=parent,
        ) if interval == _HOURLY and parent == HEARTBEATS_TABLE:
            if stored == horizon:
                return HeartbeatClassVerified(horizon=horizon)
            await connection.execute(
                text(
                    f"""
                    UPDATE {RETENTION_CLASSES}
                    SET duration = :duration
                    WHERE class_key = :class_key
                    """
                ),
                {'duration': horizon, 'class_key': HEARTBEAT_CLASS_KEY},
            )
            return HeartbeatHorizonUpdated(previous_horizon=stored, horizon=horizon)
        case RetentionClassRow():
            raise HistoryContractError(
                'heartbeat class row carries a non-heartbeat shape'
            )


